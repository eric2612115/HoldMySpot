const usdMinor = (cents: number): LocalMoney => ({ currency: 'USD', minor: cents });

type ItemSeed = Omit<Item, 'retailCents' | 'shopId'>;

function shop(s: Omit<Shop, 'items'>, items: ItemSeed[]): Shop {
  return {
    ...s,
    items: items.map((i) => ({ ...i, shopId: s.id, retailCents: localToUsdCents(i.retail, DEFAULT_RULES.fxTwdPerUsd) })),
  };
}

