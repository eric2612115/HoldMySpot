function reliability(completed: number, lapsed: number, rejected: number): Reliability {
  const total = completed + lapsed + rejected;
  return {
    score: total === 0 ? 100 : Math.round((100 * completed) / total),
    claimsCompleted: completed,
    claimsLapsed: lapsed,
    proofsRejected: rejected,
  };
}

