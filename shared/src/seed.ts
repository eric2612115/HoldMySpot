/**
 * A point `east` and `north` metres from `origin` (flat-earth approximation,
 * good to well under a metre over a few kilometres).
 */
export function offsetLngLat(origin: LngLat, east: number, north: number): LngLat {
  const lat0 = (origin[1] * Math.PI) / 180;
  const lng = origin[0] + east / (111_320 * Math.cos(lat0));
  const lat = origin[1] + north / 110_574;
  return [Math.round(lng * 1e6) / 1e6, Math.round(lat * 1e6) / 1e6];
}

