/** Small deterministic random generator (same as the web app's `seeded`). */
export function seeded(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function findShop(shopId: string): Shop | undefined {
  return SEED_SHOPS.find((s) => s.id === shopId);
}

export function findItem(itemId: string): Item | undefined {
  for (const s of SEED_SHOPS) {
    const item = s.items.find((i) => i.id === itemId);
    if (item) return item;
  }
  return undefined;
}

/** The shop that sells an item. */
export function shopOfItem(itemId: string): Shop | undefined {
  return SEED_SHOPS.find((s) => s.items.some((i) => i.id === itemId));
}
